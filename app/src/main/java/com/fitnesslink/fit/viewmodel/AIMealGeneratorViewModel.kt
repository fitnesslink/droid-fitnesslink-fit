package com.fitnesslink.fit.viewmodel

import androidx.compose.runtime.getValue
import androidx.compose.runtime.mutableStateOf
import androidx.compose.runtime.setValue
import androidx.lifecycle.ViewModel
import com.fitnesslink.fit.model.MealType
import com.fitnesslink.fit.model.NutritionGoal
import com.fitnesslink.fit.network.ApiClient
import com.fitnesslink.fit.network.ApiError
import com.fitnesslink.fit.network.NetworkMonitor
import com.fitnesslink.fit.network.dto.DraftMeal
import com.fitnesslink.fit.network.dto.GenerateMealContext
import com.fitnesslink.fit.network.dto.GenerateMealSuggestionRequest
import com.fitnesslink.fit.network.dto.GenerateMealSuggestionResponse
import com.fitnesslink.fit.nutrition.NutritionGoalsStore
import java.util.Locale
import kotlin.math.roundToInt

/**
 * Drives the "AI Suggestions" sheet in Build Meal (port of iOS
 * `AIMealGeneratorViewModel`). The user describes the meal and sets diet /
 * allergy / avoid constraints, then explicitly taps Generate — nothing fires
 * on open and nothing is persisted here; a tapped suggestion is staged in
 * the builder and saved through the normal flow.
 */
class AIMealGeneratorViewModel : ViewModel() {
    var mealType by mutableStateOf(MealType.BREAKFAST)
    var prompt by mutableStateOf("")
    var calorieTarget by mutableStateOf<Int?>(null)
    var proteinTarget by mutableStateOf<Double?>(null)
    var fatTarget by mutableStateOf<Double?>(null)
    var carbsTarget by mutableStateOf<Double?>(null)
    var dietaryPreferences by mutableStateOf<Set<String>>(emptySet())
    var allergiesText by mutableStateOf("")
    var avoidIngredientsText by mutableStateOf("")

    var isGenerating by mutableStateOf(false)
        private set
    var errorMessage by mutableStateOf<String?>(null)
        private set
    var suggestions by mutableStateOf<List<DraftMeal>>(emptyList())
        private set
    var hasGenerated by mutableStateOf(false)
        private set

    private var seeded = false
    private var profileSeeded = false

    val canGenerate: Boolean get() = !isGenerating && NetworkMonitor.isConnected.value

    /** Seed targets as a share of the daily goal (30 %, snacks 10 %). Once. */
    fun seed(mealType: MealType, goal: NutritionGoal) {
        this.mealType = mealType
        if (seeded) return
        seeded = true
        val share = if (mealType == MealType.SNACK) 0.10 else 0.30
        if (calorieTarget == null && goal.calorieGoal > 0) calorieTarget = (goal.calorieGoal * share).roundToInt()
        if (proteinTarget == null && goal.proteinTarget > 0) proteinTarget = (goal.proteinTarget * share).roundToInt().toDouble()
        if (fatTarget == null && goal.fatTarget > 0) fatTarget = (goal.fatTarget * share).roundToInt().toDouble()
        if (carbsTarget == null && goal.carbsTarget > 0) carbsTarget = (goal.carbsTarget * share).roundToInt().toDouble()
    }

    /** Pre-fill allergies / diet chips from the saved nutrition profile (agent A's store). */
    fun seedFromProfile() {
        if (profileSeeded) return
        profileSeeded = true
        val profile = runCatching { NutritionGoalsStore.profile.value }.getOrNull() ?: return
        if (allergiesText.isBlank()) allergiesText = profile.allergies.joinToString(", ")
        if (dietaryPreferences.isEmpty()) dietaryPreferences = profile.dietaryPreferences.filter { it in dietOptions }.toSet()
    }

    suspend fun generate() {
        if (!NetworkMonitor.isConnected.value) {
            errorMessage = "You need an active internet connection to generate meal ideas."
            return
        }
        isGenerating = true
        errorMessage = null
        suggestions = emptyList()
        try {
            val context = GenerateMealContext(
                mealType = mealType.wireValue,
                calorieTarget = calorieTarget, proteinTarget = proteinTarget, fatTarget = fatTarget, carbsTarget = carbsTarget,
                dietaryPreferences = dietOptions.filter { it in dietaryPreferences }.takeIf { it.isNotEmpty() },
                allergies = splitList(allergiesText),
                avoidIngredients = splitList(avoidIngredientsText)
            )
            val trimmed = prompt.trim()
            val response = try {
                ApiClient.nutritionAiApi.generateMealSuggestions(GenerateMealSuggestionRequest(prompt = trimmed.ifEmpty { null }, context = context))
            } catch (e: ApiError.ServerError) {
                // Handled failures carry the envelope in the body (400 / 422 / 429 / 502 / 504).
                e.decodeBody(ApiClient.gson, GenerateMealSuggestionResponse::class.java) ?: throw e
            }
            val meals = response.suggestions.orEmpty()
            if (response.success && meals.isNotEmpty()) {
                suggestions = meals
            } else {
                errorMessage = friendlyMessage(response.errorReasonCode, response.errorDetail)
            }
        } catch (_: ApiError.Offline) {
            errorMessage = "You need an active internet connection to generate meal ideas."
        } catch (_: Exception) {
            errorMessage = "Something went wrong generating meal ideas. Please try again."
        } finally {
            isGenerating = false
            hasGenerated = true
        }
    }

    companion object {
        val dietOptions: List<String> = listOf(
            "Balanced", "High protein", "Low carb", "Keto", "Mediterranean",
            "Vegetarian", "Vegan", "Pescatarian", "Paleo", "Gluten-free", "Dairy-free"
        )

        /** Comma / newline separated → trimmed non-empty items, or null when none. */
        fun splitList(text: String): List<String>? =
            text.split(',', '\n').map { it.trim() }.filter { it.isNotEmpty() }.takeIf { it.isNotEmpty() }

        private fun friendlyMessage(reasonCode: String?, detail: String?): String {
            val code = reasonCode?.lowercase(Locale.US)
            return when {
                code == "allergen_violation" -> "The ideas included something you're avoiding. Please try again."
                code == "no_suggestions" -> "Couldn't come up with a meal for that. Try a different description."
                code == "rate_limited" -> "You've generated a lot of ideas recently. Please try again in a little while."
                code == "gemini_unavailable" || code == "timeout" -> "The AI service is temporarily unavailable. Please try again shortly."
                code == "schema_violation" -> "The AI returned an unexpected response. Please try again."
                code != null && (code.contains("unsafe") || code.contains("safety")) -> "That request couldn't be processed. Try describing a normal meal."
                else -> detail ?: "Couldn't generate meal ideas. Please try a different prompt."
            }
        }
    }
}
