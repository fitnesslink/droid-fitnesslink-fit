import com.fitnesslink.fit.network.dto.ApplyMealPlanWeekResult
import com.fitnesslink.fit.network.dto.DraftMealPlanDay
import com.fitnesslink.fit.network.dto.DraftMealPlanWeek
import com.fitnesslink.fit.network.dto.DraftPlannedMeal
import com.fitnesslink.fit.network.dto.GenerateMealPlanWeekContext
import com.fitnesslink.fit.network.dto.GenerateMealPlanWeekRequest
import com.fitnesslink.fit.network.dto.GenerateMealPlanWeekResponse
