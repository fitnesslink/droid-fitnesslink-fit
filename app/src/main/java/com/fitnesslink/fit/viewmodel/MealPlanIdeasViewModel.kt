import java.util.Locale

/**
 * Drives the "Meal Plan Ideas" flow (port of iOS `MealPlanIdeasViewModel`):
 * description + structured constraints → one week-sized AI call →
 * review/toggle each idea → explicit approval writes the selected meals
 * onto the planner via [MealPlanStore.applyIdeas]. Nothing is persisted
 * until apply succeeds, and the copy is deliberately "ideas", never
 * recommendations.
 *
 * Shared between the request sheet and the review screen (same nav-graph
 * scoped instance).
 */
class MealPlanIdeasViewModel : ViewModel() {
    // Inputs
    var weekStart by mutableStateOf(MealPlanDay.string(MealPlanDay.weekStart(Date())))
    var prompt by mutableStateOf("")
    var dailyCalorieTarget by mutableStateOf<Int?>(null)
    var dailyProteinTarget by mutableStateOf<Double?>(null)
    var dailyFatTarget by mutableStateOf<Double?>(null)
    var dailyCarbsTarget by mutableStateOf<Double?>(null)
    var mealTypes by mutableStateOf<Set<MealType>>(MealType.entries.toSet())
    var dietaryPreferences by mutableStateOf<Set<String>>(emptySet())
    var allergiesText by mutableStateOf("")
    var avoidIngredientsText by mutableStateOf("")
    var cuisinesText by mutableStateOf("")
    var maxPrepMinutes by mutableStateOf<Int?>(null)
    var cookingSkill by mutableStateOf<String?>(null)
    var budget by mutableStateOf<String?>(null)

    // State
    var isGenerating by mutableStateOf(false)
        private set
    var isApplying by mutableStateOf(false)
        private set
    var errorMessage by mutableStateOf<String?>(null)
        private set
    var applyErrorMessage by mutableStateOf<String?>(null)
        private set
    var hasGenerated by mutableStateOf(false)
        private set
    var generationId by mutableStateOf<String?>(null)
        private set
    var draft by mutableStateOf<DraftMealPlanWeek?>(null)
    /** Deselected ideas keyed by `"${day}|${mealType}|${index}"`. */
    var deselected by mutableStateOf<Set<String>>(emptySet())
        private set

    private var seeded = false
    private var profileSeeded = false

    // MARK: - Seeding

    fun seed(weekStart: String, goal: NutritionGoal) {
        this.weekStart = MealPlanStore.weekBounds(weekStart).first
        if (seeded) return
        seeded = true
        if (dailyCalorieTarget == null && goal.calorieGoal > 0) dailyCalorieTarget = goal.calorieGoal
        if (dailyProteinTarget == null && goal.proteinTarget > 0) dailyProteinTarget = goal.proteinTarget.toDouble()
        if (dailyFatTarget == null && goal.fatTarget > 0) dailyFatTarget = goal.fatTarget.toDouble()
        if (dailyCarbsTarget == null && goal.carbsTarget > 0) dailyCarbsTarget = goal.carbsTarget.toDouble()
    }

    fun seedFromProfile() {
        if (profileSeeded) return
        profileSeeded = true
        val profile = runCatching { NutritionGoalsStore.profile.value }.getOrNull() ?: return
        if (allergiesText.isBlank()) allergiesText = profile.allergies.joinToString(", ")
        if (dietaryPreferences.isEmpty()) dietaryPreferences = profile.dietaryPreferences.filter { it in dietOptions }.toSet()
    }

    // MARK: - Generate

    val canGenerate: Boolean get() = !isGenerating && mealTypes.isNotEmpty() && NetworkMonitor.isConnected.value

    suspend fun generate() {
        if (!NetworkMonitor.isConnected.value) {
            errorMessage = "You need an active internet connection to generate meal plan ideas."
            return
        }
        if (mealTypes.isEmpty()) {
            errorMessage = "Pick at least one meal to plan."
            return
        }
        isGenerating = true
        errorMessage = null
        draft = null
        deselected = emptySet()
        generationId = null
        try {
            val context = GenerateMealPlanWeekContext(
                dailyCalorieTarget = dailyCalorieTarget, dailyProteinTarget = dailyProteinTarget,
                dailyFatTarget = dailyFatTarget, dailyCarbsTarget = dailyCarbsTarget,
                mealTypes = MealType.entries.filter { it in mealTypes }.map { it.wireValue },
                dietaryPreferences = dietOptions.filter { it in dietaryPreferences }.takeIf { it.isNotEmpty() },
                allergies = AIMealGeneratorViewModel.splitList(allergiesText),
                avoidIngredients = AIMealGeneratorViewModel.splitList(avoidIngredientsText),
                cuisinePreferences = AIMealGeneratorViewModel.splitList(cuisinesText),
                maxPrepMinutes = maxPrepMinutes, cookingSkill = cookingSkill, budget = budget
            )
            val trimmed = prompt.trim()
            val response = try {
                ApiClient.nutritionAiApi.generateMealPlanWeek(GenerateMealPlanWeekRequest(weekStart = weekStart, prompt = trimmed.ifEmpty { null }, context = context))
            } catch (e: ApiError.ServerError) {
                e.decodeBody(ApiClient.gson, GenerateMealPlanWeekResponse::class.java) ?: throw e
            }
            val week = response.draft
            if (response.success && week != null && week.allMeals().isNotEmpty()) {
                draft = week
                generationId = response.generationId
            } else {
                errorMessage = friendlyMessage(response.errorReasonCode, response.errorDetail)
            }
        } catch (_: ApiError.Offline) {
            errorMessage = "You need an active internet connection to generate meal plan ideas."
        } catch (_: Exception) {
            errorMessage = "Something went wrong generating ideas. Please try again."
        } finally {
            isGenerating = false
            hasGenerated = true
        }
    }

    // MARK: - Review

    fun key(day: DraftMealPlanDay, index: Int): String = "${day.day}|${day.meals.getOrNull(index)?.mealType}|$index"

    fun isSelected(day: DraftMealPlanDay, index: Int): Boolean = key(day, index) !in deselected

    fun toggle(day: DraftMealPlanDay, index: Int) {
        val k = key(day, index)
        deselected = if (k in deselected) deselected - k else deselected + k
    }

    fun selectedMeals(day: DraftMealPlanDay): List<DraftPlannedMeal> = day.meals.filterIndexed { i, _ -> isSelected(day, i) }

    val selectedCount: Int get() = draft?.days?.sumOf { selectedMeals(it).size } ?: 0

    val totalCount: Int get() = draft?.allMeals()?.size ?: 0

    fun selectedCalories(day: DraftMealPlanDay): Int = selectedMeals(day).sumOf { it.meal.calories }

    val averageDailyCalories: Int?
        get() {
            val totals = draft?.days?.map { selectedCalories(it) }?.filter { it > 0 } ?: return null
            if (totals.isEmpty()) return null
            return totals.sum() / totals.size
        }

    val approvedMeals: List<ApplyMealPlanWeekMeal>
        get() = draft?.days?.flatMap { day -> selectedMeals(day).map { ApplyMealPlanWeekMeal(day.day, it.mealType, it.meal) } } ?: emptyList()

    // MARK: - Apply (approval)

    /** `mode` = "merge" | "replace". Null on failure (message in [applyErrorMessage]). */
    suspend fun apply(mode: String): ApplyMealPlanWeekResult? {
        val meals = approvedMeals
        if (meals.isEmpty()) {
            applyErrorMessage = "Select at least one idea to add."
            return null
        }
        isApplying = true
        applyErrorMessage = null
        return try {
            MealPlanStore.applyIdeas(weekStart, generationId, mode, meals)
        } catch (e: Exception) {
            applyErrorMessage = applyMessage(e)
            null
        } finally {
            isApplying = false
        }
    }

    fun discard() { draft = null }

    companion object {
        val dietOptions: List<String> = AIMealGeneratorViewModel.dietOptions
        val prepOptions: List<Int> = listOf(15, 30, 45, 60)
        val skillOptions: List<String> = listOf("Beginner", "Comfortable", "Confident")
        val budgetOptions: List<String> = listOf("Tight", "Moderate", "Flexible")

        fun DraftMealPlanWeek.allMeals(): List<DraftPlannedMeal> = days.flatMap { it.meals }

        private fun friendlyMessage(reasonCode: String?, detail: String?): String {
            val code = reasonCode?.lowercase(Locale.US)
            return when {
                code == "allergen_violation" -> "The ideas included something you're avoiding. Please try again."
                code == "no_suggestions" || code == "incomplete_week" -> "Couldn't put together a full week for that. Try a different description."
                code == "rate_limited" -> "You've generated a lot of ideas recently. Please try again in a little while."
                code == "gemini_unavailable" || code == "timeout" -> "The AI service is temporarily unavailable. Please try again shortly."
                code == "schema_violation" -> "The AI returned an unexpected response. Please try again."
                code == "invalid_week_start" -> detail ?: "That week couldn't be used. Please try again."
                code != null && (code.contains("unsafe") || code.contains("safety") || code.contains("medical") || code.contains("pii")) ->
                    "That request couldn't be processed. Try describing the kinds of meals you'd like."
                else -> detail ?: "Couldn't generate meal plan ideas. Please try a different description."
            }
        }

        private fun applyMessage(e: Throwable): String = when {
            e is ApiError.Offline -> "You need an active internet connection to add these ideas."
            e is ApiError.ServerError && e.isBadRequest -> e.errorDetail ?: e.envelope?.displayMessage ?: "Couldn't add the ideas. Please try again."
            else -> "Couldn't add the ideas to your plan. Please try again."
        }
    }
}
